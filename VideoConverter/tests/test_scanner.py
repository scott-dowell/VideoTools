def test_walk_folder_events(tmp_path):
    """Two subdirectories each produce one folder event with correct rel path."""
    sub_a = tmp_path / "ShowA"
    sub_b = tmp_path / "ShowB"
    sub_a.mkdir()
    sub_b.mkdir()
    shutil.copy(FIXTURES_DIR / "h264_short.mkv",   sub_a / "ep01.mkv")
    shutil.copy(FIXTURES_DIR / "h264_mp4_aac.mp4", sub_b / "ep02.mp4")

    folders, done, _, _ = _collect(tmp_path)

    folder_names = {ev["folder"] for ev in folders}
    assert "ShowA" in folder_names
    assert "ShowB" in folder_names
    assert done["total_files"] == 2


