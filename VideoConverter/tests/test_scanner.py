def test_walk_corrupt_file_emits_warning(tmp_path):
    """A zero-byte .mkv yields a warning event; walk continues normally."""
    # Real file alongside the bad one so the folder is still yielded
    shutil.copy(FIXTURES_DIR / "h264_short.mkv", tmp_path / "good.mkv")
    (tmp_path / "bad.mkv").write_bytes(b"")

    folders, done, warnings, _ = _collect(tmp_path)

    # Warning for the empty file
    assert any("bad.mkv" in w["path"] for w in warnings)
    # Good file still scanned
    names = {f["name"] for f in _all_files(folders)}
    assert "good.mkv" in names
    assert done["total_files"] == 1


