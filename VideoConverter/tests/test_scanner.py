def _collect(root, **kwargs):
    """
    Run scanner.walk(root) and return a tuple:
      (folder_events, done_event, warning_events, error_events)
    """
    folders  = []
    done     = None
    warnings = []
    errors   = []
    for event in scanner.walk(str(root)):
        t = event.get("type")
        if t == "folder":
            folders.append(event)
        elif t == "done":
            done = event
        elif t == "warning":
            warnings.append(event)
        elif t == "error":
            errors.append(event)
    return folders, done, warnings, errors


def _all_files(folder_events):
    """Flatten all file dicts from a list of folder events."""
    return [f for ev in folder_events for f in ev["files"]]


