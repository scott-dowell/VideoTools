def test_walk_skips_db_done(tmp_path, fresh_db):
    """File with status='done' in DB is silently excluded from folder events."""
    dest = tmp_path / "h264_short.mkv"
    shutil.copy(FIXTURES_DIR / "h264_short.mkv", dest)

    mtime  = dest.stat().st_mtime
    rec_id = db.upsert_pending(str(dest), mtime)
    db.mark_running(rec_id, "2026-01-01T00:00:00Z")
    db.mark_done(
        rec_id,
        str(tmp_path / "converted" / "h264_short.mkv"),
        output_size_mb=0.5,
        saved_mb=0.7,
        saved_pct=58,
        completed_at="2026-01-01T00:01:00Z",
    )

    folders, done, _, _ = _collect(tmp_path)
    assert done["total_files"] == 0
    assert folders == []


def test_walk_requeues_replaced_file(tmp_path, fresh_db):
    """Same path but different mtime is treated as a new file."""
    dest = tmp_path / "h264_short.mkv"
    shutil.copy(FIXTURES_DIR / "h264_short.mkv", dest)

    mtime  = dest.stat().st_mtime
    rec_id = db.upsert_pending(str(dest), mtime)
    db.mark_running(rec_id, "2026-01-01T00:00:00Z")
    db.mark_done(
        rec_id,
        str(tmp_path / "converted" / "h264_short.mkv"),
        output_size_mb=0.5,
        saved_mb=0.7,
        saved_pct=58,
        completed_at="2026-01-01T00:01:00Z",
    )

    # Simulate in-place replacement by nudging mtime forward
    new_mtime = mtime + 1.0
    os.utime(str(dest), (new_mtime, new_mtime))

    folders, done, _, _ = _collect(tmp_path)
    assert done["total_files"] == 1, "New mtime should bypass DB skip"
    assert len(folders) == 1


def test_walk_running_emits_warning(tmp_path, fresh_db):
    """File with status='running' in DB emits a warning and is not yielded."""
    dest = tmp_path / "h264_short.mkv"
    shutil.copy(FIXTURES_DIR / "h264_short.mkv", dest)

    mtime  = dest.stat().st_mtime
    rec_id = db.upsert_pending(str(dest), mtime)
    db.mark_running(rec_id, "2026-01-01T00:00:00Z")

    folders, done, warnings, _ = _collect(tmp_path)
    assert done["total_files"] == 0
    assert folders == []
    assert any(str(dest).replace("\\", "/") in w["path"].replace("\\", "/")
               for w in warnings)


